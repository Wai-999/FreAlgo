// Production dependency licence audit → docs/licenses.md (summary + flagged packages).
// Usage: node scripts/ops/license-audit.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], {
  maxBuffer: 64 * 1024 * 1024,
})
  .toString()
  .trim()
  .split('\n')
  .slice(1);
const pkgs = new Map();
for (const dir of out) {
  try {
    const pj = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const lic =
      typeof pj.license === 'string'
        ? pj.license
        : (pj.license?.type ?? (pj.licenses?.map?.((l) => l.type).join(' OR ') || 'UNKNOWN'));
    pkgs.set(`${pj.name}@${pj.version}`, lic);
  } catch {
    // ignore unreadable entries
  }
}
const byLicense = new Map();
for (const [name, lic] of pkgs) {
  if (!byLicense.has(lic)) byLicense.set(lic, []);
  byLicense.get(lic).push(name);
}
const PERMISSIVE =
  /^(\(?)(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|Unlicense|CC0-1\.0|Python-2\.0|Unicode-3\.0)( OR (MIT|Apache-2\.0|CC0-1\.0))*(\)?)$/;
const flagged = [...pkgs].filter(([, lic]) => !PERMISSIVE.test(lic));
// Reviewed assessments for known non-allow-listed packages (update when the list changes).
const NOTES = {
  'caniuse-lite':
    'Browser-support data used at build time by browserslist (via Next.js). CC-BY-4.0 requires attribution only; not redistributed as content.',
  '@img/sharp-libvips-darwin-arm64':
    'libvips, dynamically linked by sharp (optional Next.js image optimiser, unused because FreAlgo serves no images). LGPL permits dynamic linking; the library is unmodified.',
  '@img/sharp-libvips-linux-arm64': 'As above (Linux build).',
  '@img/sharp-libvips-linuxmusl-x64': 'As above (Alpine build).',
  '@img/sharp-libvips-linuxmusl-arm64': 'As above (Alpine build).',
  elkjs:
    'Graph layout used only by Prisma Studio (pulled in via prisma ← @prisma/client 7); never loaded by FreAlgo at runtime. EPL-2.0 is weak, file-level copyleft and the code is unmodified.',
  '@visx/vendor':
    'Prisma Studio chart dependency (same path as elkjs); MIT and ISC (permissive, dual-declared).',
};
const noteFor = (name) => NOTES[name.slice(0, name.lastIndexOf('@'))] ?? 'Needs review.';
const lines = [
  '# Licence audit (production dependencies)',
  '',
  `Generated by \`node scripts/ops/license-audit.mjs\` on ${new Date().toISOString().slice(0, 10)} from \`npm ls --omit=dev\`.`,
  `${pkgs.size} packages are shipped in production images.`,
  '',
  '| Licence | Packages |',
  '| --- | --- |',
  ...[...byLicense]
    .sort((a, b) => b[1].length - a[1].length)
    .map(([lic, names]) => `| ${lic} | ${names.length} |`),
  '',
  '## Packages needing review (not on the permissive allow-list)',
  '',
  ...(flagged.length
    ? flagged.map(([n, l]) => `- \`${n}\` (${l}): ${noteFor(n)}`)
    : ['None. Every production dependency uses a permissive licence.']),
  '',
  'Conclusion: no strong-copyleft (GPL/AGPL) code ships in production images. The packages above were reviewed and are acceptable for this use.',
  '',
  '## Data and content',
  '',
  '| Asset | Source | Licence / terms |',
  '| --- | --- | --- |',
  '| Country boundaries (`public/geo/*`) | Natural Earth 1:110m via world-atlas@2.0.2 | Public domain (data); ISC (packaging), attribution kept on /about |',
  '| ISO 3166-1 codes and English names | i18n-iso-countries@7.14.0 | MIT |',
  '| Regions, official languages | Unicode CLDR via cldr-core@48.2.0 | Unicode License v3 |',
  '| Headlines and excerpts | Publisher RSS/Atom feeds | Publisher terms; feeds stay paused until an operator records a terms review; links always point to the original; no images; no full text |',
  '| Fixture outlets and articles | Written for this project | Fictional; badged in the UI |',
  '',
];
writeFileSync('docs/licenses.md', lines.join('\n'));
console.log(`audited ${pkgs.size} packages; flagged ${flagged.length}`);
for (const [n, l] of flagged) console.log(`  ${n}: ${l}`);

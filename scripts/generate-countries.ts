/**
 * Regenerates prisma/data/countries.json from pinned, permissively licensed reference data:
 *   - i18n-iso-countries (MIT): ISO 3166-1 alpha-2/alpha-3/numeric codes and English names
 *   - cldr-core (Unicode License v3): UN M49 region containment and official-language status
 *
 * Run: node --import tsx scripts/generate-countries.ts
 * The output is committed so seeding never depends on network access or package internals.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const read = (p: string) => JSON.parse(readFileSync(require.resolve(p), 'utf8'));

type CodeRow = [alpha2: string, alpha3: string, numeric: string, iso31662: string];
const codes: CodeRow[] = read('i18n-iso-countries/codes.json');
const en: { countries: Record<string, string | string[]> } = read(
  'i18n-iso-countries/langs/en.json',
);
const containment: Record<string, { _contains?: string[]; _grouping?: string }> = read(
  'cldr-core/supplemental/territoryContainment.json',
).supplemental.territoryContainment;
const territoryInfo: Record<
  string,
  { languagePopulation?: Record<string, { _officialStatus?: string }> }
> = read('cldr-core/supplemental/territoryInfo.json').supplemental.territoryInfo;

// UN M49 names (public standard). Only the codes CLDR uses for containment are needed.
const M49: Record<string, string> = {
  '002': 'Africa',
  '019': 'Americas',
  '142': 'Asia',
  '150': 'Europe',
  '009': 'Oceania',
  '010': 'Antarctica',
  '014': 'Eastern Africa',
  '017': 'Middle Africa',
  '015': 'Northern Africa',
  '018': 'Southern Africa',
  '011': 'Western Africa',
  '029': 'Caribbean',
  '013': 'Central America',
  '005': 'South America',
  '021': 'Northern America',
  '143': 'Central Asia',
  '030': 'Eastern Asia',
  '034': 'Southern Asia',
  '035': 'South-Eastern Asia',
  '145': 'Western Asia',
  '151': 'Eastern Europe',
  '154': 'Northern Europe',
  '039': 'Southern Europe',
  '155': 'Western Europe',
  '053': 'Australia and New Zealand',
  '054': 'Melanesia',
  '057': 'Micronesia',
  '061': 'Polynesia',
};
const REGIONS = ['002', '019', '142', '150', '009'];

// Short, commonly used English display names. ISO long-form names remain available in ISO
// documentation; we do not take positions on disputed sovereignty in display names.
const DISPLAY_OVERRIDES: Record<string, string> = {
  US: 'United States',
  GB: 'United Kingdom',
  RU: 'Russia',
  KR: 'South Korea',
  KP: 'North Korea',
  CD: 'DR Congo',
  CG: 'Republic of the Congo',
  TW: 'Taiwan',
  PS: 'Palestine',
  IR: 'Iran',
  SY: 'Syria',
  VN: 'Vietnam',
  LA: 'Laos',
  BO: 'Bolivia',
  VE: 'Venezuela',
  TZ: 'Tanzania',
  MD: 'Moldova',
  MK: 'North Macedonia',
  FM: 'Micronesia',
  BN: 'Brunei',
  CI: "Côte d'Ivoire",
  CZ: 'Czechia',
  VA: 'Vatican City',
};

function parentOf(code: string): string | undefined {
  for (const [parent, entry] of Object.entries(containment)) {
    if (parent.includes('-status-')) continue;
    if (!/^\d{3}$/.test(parent) || entry._grouping === 'true') continue;
    if (entry._contains?.includes(code)) return parent;
  }
  return undefined;
}

const rows = codes
  .map(([iso2, iso3, numeric]) => {
    const names = en.countries[iso2];
    const fallback = Array.isArray(names) ? names[0] : names;
    const name = DISPLAY_OVERRIDES[iso2] ?? fallback;
    if (!name) throw new Error(`Missing English name for ${iso2}`);
    const sub = parentOf(iso2);
    // Walk up the containment tree (e.g. 014 -> 202 -> 002) until a top-level region is reached.
    let region = sub;
    for (let i = 0; region && !REGIONS.includes(region) && i < 5; i++) region = parentOf(region);
    if (iso2 === 'AQ') region = '010';
    const languages = Object.entries(territoryInfo[iso2]?.languagePopulation ?? {})
      .filter(
        ([, v]) => v._officialStatus === 'official' || v._officialStatus === 'de_facto_official',
      )
      .map(([lang]) => lang.replace('_', '-'))
      .sort();
    return {
      iso2,
      iso3,
      // XK (Kosovo) uses a user-assigned code without an ISO numeric code.
      isoNumeric: iso2 === 'XK' ? null : numeric,
      name,
      region: region ? (M49[region] ?? null) : null,
      subregion: sub && !REGIONS.includes(sub) ? (M49[sub] ?? null) : null,
      officialLanguages: languages,
    };
  })
  .sort((a, b) => a.iso2.localeCompare(b.iso2));

const out = path.resolve('prisma/data/countries.json');
writeFileSync(
  out,
  JSON.stringify(
    {
      _provenance:
        'Generated by scripts/generate-countries.ts from i18n-iso-countries@7.14.0 (MIT) and cldr-core@48.2.0 (Unicode License v3). Display names: see DISPLAY_OVERRIDES.',
      countries: rows,
    },
    null,
    2,
  ) + '\n',
);
console.log(`Wrote ${rows.length} countries to ${out}`);
